#!/usr/bin/env node
// Generate n8n/lni-inquiry-reports.workflow.json from src/. The Code nodes get the src/ functions pasted in, so
// src/ stays the master copy: change src/, run `npm run build:workflow`, then re-import the workflow in n8n.
// The workflow only creates Gmail drafts. It has no send node, and tests/workflow.test.cjs checks that.
// Usage: node scripts/build-workflow.cjs [--check]   (--check exits 1 if the committed file is out of date)
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'n8n', 'lni-inquiry-reports.workflow.json');

// Each src file and the files it requires, in paste order.
const DEPS = {
  'inquiry.cjs': [],
  'understand.cjs': [],
  'lni.cjs': [],
  'report.cjs': [],
};

/** Paste src files into a Code node, dropping require and module.exports lines that n8n can't run. */
function bundle(files, adapter) {
  const order = [];
  const add = (f) => { for (const d of DEPS[f]) add(d); if (!order.includes(f)) order.push(f); };
  files.forEach(add);
  const code = order.map((f) => `// ---- src/${f} (generated by scripts/build-workflow.cjs; edit src/, not this node) ----\n` +
    fs.readFileSync(path.join(ROOT, 'src', f), 'utf8')
      .split('\n')
      .filter((l) => !/^const .* = require\(/.test(l) && !/^module\.exports\b/.test(l))
      .join('\n')
      .trim());
  return `${code.join('\n\n')}\n\n// ---- Adapter ----\n${adapter.trim()}\n`;
}

const id = (name) => {
  const h = crypto.createHash('sha1').update(`raeltek-lni-reports:${name}`).digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
};

const nodes = [];
const node = (name, type, typeVersion, [x, y], parameters, extra = {}) => {
  nodes.push({ parameters, type, typeVersion, position: [x * 220, y * 200], id: id(name), name, ...extra });
};
// Everything inside the loop handles one inquiry at a time, so Code nodes run once over their single item.
const code = (name, pos, files, adapter) => node(name, 'n8n-nodes-base.code', 2, pos, { jsCode: bundle(files, adapter) });
const ifNode = (name, pos, expression) => node(name, 'n8n-nodes-base.if', 2.2, pos, {
  conditions: {
    options: { caseSensitive: true, leftValue: '', typeValidation: 'strict', version: 2 },
    conditions: [{ id: id(`${name}:condition`), leftValue: expression, rightValue: '', operator: { type: 'boolean', operation: 'true', singleValue: true } }],
    combinator: 'and',
  },
  options: {},
});
// Socrata returns a JSON array, which n8n would split into one item per row; read it as text instead.
const socrata = (name, pos, url) => node(name, 'n8n-nodes-base.httpRequest', 4.2, pos, {
  url,
  options: { response: { response: { responseFormat: 'text', outputPropertyName: 'body' } }, timeout: 120000 },
});
const ollama = (name, pos, body) => node(name, 'n8n-nodes-base.httpRequest', 4.2, pos, {
  method: 'POST',
  url: "={{ $('Settings').first().json.OLLAMA_URL }}/api/chat",
  sendBody: true,
  specifyBody: 'json',
  jsonBody: body,
  options: { timeout: 300000 },
}, { onError: 'continueRegularOutput' });
const settings = "const s = $('Settings').first().json;";
const today = "const today = $now.setZone('America/Los_Angeles').toISODate();";

// ---- Nodes ----
node('New inquiry email', 'n8n-nodes-base.gmailTrigger', 1.2, [0, 0], {
  pollTimes: { item: [{ mode: 'everyX', value: 5, unit: 'minutes' }] },
  simple: false,
  // Gmail search ignores the brackets; Check inquiries requires the exact [L&I Inquiry] tag.
  filters: { q: 'subject:"L&I Inquiry" in:inbox -from:me' },
  options: {},
});

node('Settings', 'n8n-nodes-base.set', 3.4, [1, 0], {
  assignments: {
    assignments: [
      // Who may ask for reports: one address (jane@example.com) or whole domain (@example.com) per line.
      // Emails from anyone else are ignored without a reply. Fill this in n8n, not in Git.
      ['ALLOWED_SENDERS', 'string', ''],
      // Only trust the From address when Gmail's DMARC check passed for it. Turn off only for a sender whose
      // domain has no DMARC record, and only if you are sure of them.
      ['REQUIRE_DMARC_PASS', 'boolean', true],
      ['DEFAULT_DAYS', 'number', 14],
      ['MAX_DAYS', 'number', 90],
      // Rows printed in one PDF.
      ['MAX_ROWS', 'number', 300],
      // Optional free Socrata app token (data.wa.gov › Developer settings) to avoid throttling.
      ['SOCRATA_APP_TOKEN', 'string', ''],
      ['SIGNATURE', 'string', 'Josh\nRaeltek'],
      // Ollama and Gotenberg on the host machine, seen from inside the n8n container.
      ['OLLAMA_URL', 'string', 'http://host.docker.internal:11434'],
      ['OLLAMA_MODEL', 'string', 'qwen3:4b'],
      ['GOTENBERG_URL', 'string', 'http://host.docker.internal:3010'],
    ].map(([name, type, value]) => ({ id: id(`Settings:${name}`), name, value, type })),
  },
  options: {},
}, { executeOnce: true });

node('Check inquiries', 'n8n-nodes-base.code', 2, [2, 0], { jsCode: bundle(['inquiry.cjs'], `
${settings}
// Ignored emails are listed in this node's output in n8n's execution log, with the reason, but get no reply.
const results = $('New inquiry email').all().map((i) => checkInquiry({
  email: i.json, allowList: s.ALLOWED_SENDERS, requireDmarc: s.REQUIRE_DMARC_PASS !== false,
}));
const ignored = results.filter((r) => !r.ok);
if (ignored.length) console.log('Ignored:', JSON.stringify(ignored.map((r) => ({ from: r.sender.address, reason: r.reason }))));
return results.filter((r) => r.ok).map((r) => ({ json: r }));
`) });

node('Loop over inquiries', 'n8n-nodes-base.splitInBatches', 3, [3, 0], { batchSize: 1, options: {} });

code('Prepare', [4, 1], ['understand.cjs'], `
${settings}
const inquiry = $input.first().json;
return [{ json: { inquiry, ollama_request: understandRequest({ request: inquiry.request, model: s.OLLAMA_MODEL, defaultDays: Number(s.DEFAULT_DAYS) || 14 }) } }];
`);

ollama('Understand request', [5, 1], '={{ JSON.stringify($json.ollama_request) }}');

code('Plan query', [6, 1], ['understand.cjs', 'lni.cjs'], `
${settings}
${today}
const { inquiry } = $('Prepare').first().json;
const u = parseUnderstanding({ ollama: $input.first().json, defaultDays: Number(s.DEFAULT_DAYS) || 14, maxDays: Number(s.MAX_DAYS) || 90 });
if (u.error) throw new Error(u.error);
if (!u.clear) return [{ json: { inquiry, clear: false, question: u.question } }];
const plan = planQuery({ query: u.query, today, appToken: s.SOCRATA_APP_TOKEN });
return [{ json: { inquiry, clear: true, query: u.query, title: describeQuery(u.query), ...plan } }];
`);

ifNode('Understood?', [7, 1], '={{ $json.clear }}');

socrata('Fetch matches', [8, 0], '={{ $json.urls.first }}');

code('Plan lookups', [9, 0], ['lni.cjs'], `
${settings}
const plan = $('Plan query').first().json;
const firstRows = parseRows($input.first().json.body, 'L&I data');
return planLookups({ query: plan.query, window: plan.window, firstRows, appToken: s.SOCRATA_APP_TOKEN }).map((l) => ({ json: l }));
`);

// One request per chunk of license numbers; one second apart to stay polite to data.wa.gov without a token.
node('Fetch lookups', 'n8n-nodes-base.httpRequest', 4.2, [10, 0], {
  url: '={{ $json.url }}',
  options: {
    response: { response: { responseFormat: 'text', outputPropertyName: 'body' } },
    timeout: 120000,
    batching: { batch: { batchSize: 1, batchInterval: 1000 } },
  },
});

code('Build report', [11, 0], ['lni.cjs', 'report.cjs'], `
${settings}
const plan = $('Plan query').first().json;
const firstRows = parseRows($('Fetch matches').first().json.body, 'L&I data');
// Fetch lookups returns one item per Plan lookups item, in the same order.
const kinds = $('Plan lookups').all().map((i) => i.json.kind);
const lookups = $input.all().map((i, k) => ({ kind: kinds[k], rows: parseRows(i.json.body, 'L&I lookup') }));
const { rows, renewedCount, truncated } = buildRows({ query: plan.query, window: plan.window, firstRows, lookups });
const generatedAt = $now.setZone('America/Los_Angeles').toFormat('LLL d, yyyy h:mm a');
const html = renderReportHtml({
  title: plan.title, query: plan.query, window: plan.window, rows, notes: plan.notes,
  stats: { renewedCount, truncated }, generatedAt, maxRows: Number(s.MAX_ROWS) || 300,
});
return [{ json: { count: rows.length, html, ollama_request: replyRequest({
  senderName: plan.inquiry.sender.name, title: plan.title, count: rows.length, model: s.OLLAMA_MODEL,
}) } }];
`);

ollama('Write reply', [12, 0], '={{ JSON.stringify($json.ollama_request) }}');

code('Report HTML', [13, 0], [], `
return [{ json: { html: $('Build report').first().json.html } }];
`);

// Gotenberg needs the page as a file called index.html.
node('HTML file', 'n8n-nodes-base.convertToFile', 1.1, [14, 0], {
  operation: 'toText',
  sourceProperty: 'html',
  binaryPropertyName: 'data',
  options: { fileName: 'index.html' },
});

node('Make PDF', 'n8n-nodes-base.httpRequest', 4.2, [15, 0], {
  method: 'POST',
  url: "={{ $('Settings').first().json.GOTENBERG_URL }}/forms/chromium/convert/html",
  sendBody: true,
  contentType: 'multipart-form-data',
  bodyParameters: {
    parameters: [
      { parameterType: 'formBinaryData', name: 'files', inputDataFieldName: 'data' },
      { name: 'preferCssPageSize', value: 'true' },
      { name: 'printBackground', value: 'true' },
    ],
  },
  options: { response: { response: { responseFormat: 'file', outputPropertyName: 'data' } }, timeout: 120000 },
});

code('Reply email', [16, 0], ['report.cjs'], `
${settings}
${today}
const plan = $('Plan query').first().json;
const report = $('Build report').first().json;
const draft = buildReply({ inquiry: plan.inquiry, title: plan.title, count: report.count, ollama: $('Write reply').first().json, signature: s.SIGNATURE });
const pdf = $input.first().binary.data;
return [{ json: { draft, threadId: plan.inquiry.threadId }, binary: { data: { ...pdf, fileName: reportFileName(plan.query, today), mimeType: 'application/pdf' } } }];
`);

// Draft › Create only. There is deliberately no send node anywhere in this workflow.
node('Draft report reply', 'n8n-nodes-base.gmail', 2.1, [17, 0], {
  resource: 'draft',
  subject: '={{ $json.draft.subject }}',
  emailType: 'html',
  message: '={{ $json.draft.body_html }}',
  options: {
    sendTo: '={{ $json.draft.to }}',
    threadId: '={{ $json.threadId }}',
    attachmentsUi: { attachmentsBinary: [{ property: 'data' }] },
  },
});

code('Clarification email', [8, 2], ['report.cjs'], `
${settings}
const plan = $input.first().json;
return [{ json: { draft: buildClarification({ inquiry: plan.inquiry, question: plan.question, signature: s.SIGNATURE }), threadId: plan.inquiry.threadId } }];
`);

node('Draft clarification', 'n8n-nodes-base.gmail', 2.1, [9, 2], {
  resource: 'draft',
  subject: '={{ $json.draft.subject }}',
  emailType: 'html',
  message: '={{ $json.draft.body_html }}',
  options: { sendTo: '={{ $json.draft.to }}', threadId: '={{ $json.threadId }}' },
});

// ---- Connections ----
const connections = {};
const link = (from, to, output = 0) => {
  connections[from] ??= { main: [] };
  while (connections[from].main.length <= output) connections[from].main.push([]);
  connections[from].main[output].push({ node: to, type: 'main', index: 0 });
};
[['New inquiry email', 'Settings'], ['Settings', 'Check inquiries'], ['Check inquiries', 'Loop over inquiries'],
  ['Prepare', 'Understand request'], ['Understand request', 'Plan query'], ['Plan query', 'Understood?'],
  ['Fetch matches', 'Plan lookups'], ['Plan lookups', 'Fetch lookups'], ['Fetch lookups', 'Build report'], ['Build report', 'Write reply'],
  ['Write reply', 'Report HTML'], ['Report HTML', 'HTML file'], ['HTML file', 'Make PDF'], ['Make PDF', 'Reply email'], ['Reply email', 'Draft report reply'],
  ['Draft report reply', 'Loop over inquiries'], ['Clarification email', 'Draft clarification'],
  ['Draft clarification', 'Loop over inquiries']].forEach(([a, b]) => link(a, b));
// Loop over inquiries: output 0 is "done", output 1 is the next inquiry.
link('Loop over inquiries', 'Prepare', 1);
link('Understood?', 'Fetch matches', 0); link('Understood?', 'Clarification email', 1);

const workflow = {
  name: 'L&I inquiry reports',
  nodes,
  connections,
  settings: { executionOrder: 'v1', timezone: 'America/Los_Angeles', saveManualExecutions: true },
  pinData: {},
  meta: { templateCredsSetupCompleted: false },
  tags: [],
};

const json = `${JSON.stringify(workflow, null, 2)}\n`;
if (require.main === module) {
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (current !== json) { console.error('n8n/lni-inquiry-reports.workflow.json is out of date; run npm run build:workflow'); process.exit(1); }
  } else {
    fs.mkdirSync(path.dirname(OUT), { recursive: true });
    fs.writeFileSync(OUT, json);
    console.log(`Wrote ${path.relative(ROOT, OUT)} (${nodes.length} nodes)`);
  }
}

module.exports = { workflow, json, OUT };
