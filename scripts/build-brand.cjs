// Writes src/brand.cjs from assets/, so the logo travels inside the n8n Code node with no file to mount.
// The logo is the website's primary transparent logo (raeltek-website public/brand), cropped to its edges and shrunk, colors and proportions unchanged.
// Run after changing assets/raeltek-logo.png: npm run build:brand
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const logo = fs.readFileSync(path.join(ROOT, 'assets', 'raeltek-logo.png')).toString('base64');
fs.writeFileSync(path.join(ROOT, 'src', 'brand.cjs'), `// Raeltek brand for the PDF report. Generated by scripts/build-brand.cjs from assets/; edit those, not this file.
// Colors match the website's palette (raeltek-website public/brand/palette.json).
const BRAND = {
  name: 'Raeltek',
  site: 'raeltek.com',
  email: 'hello@raeltek.com',
  teal: '#073F43',
  gold: '#C99B3B',
  ink: '#152D30',
  muted: '#3A5457',
  tint: '#EEF5F4',
  paleTeal: '#D9E9E8',
  rule: '#C3D9D7',
  logo: 'data:image/png;base64,${logo}',
};

module.exports = { BRAND };
`);
console.log('Wrote src/brand.cjs');
